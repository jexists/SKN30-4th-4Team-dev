/**
 * 지오코딩 후보를 **정확한 것 → 관대한 것** 순서로 만든다.
 *
 * OCR 로 뽑은 주소는 "서울특별시 강남구 테헤란로 123, 제3층 제301호" 처럼 건물 내부 상세가
 * 붙어 있어 `addressSearch` 가 ZERO_RESULT 를 낸다. 상세를 떼면 대개 맞는다.
 *
 * 시/도 단위까지 잘라 올라가는 폴백은 **의도적으로 넣지 않는다** — 자치구 중심점에 핀을
 * 꽂아 놓고 목적물처럼 보여주면 오해를 만든다. 못 찾으면 못 찾았다고 말하는 게 낫다.
 */
export function addressCandidates(raw: string): string[] {
  const base = raw
    .replace(/[()[\]]/g, ' ')
    // 마스킹 잔재(*** 등)가 섞여 들어오는 경우 방어. 주소는 마스킹 대상이 아니지만
    // 인접한 이름·연락처의 치환 문자가 같은 줄에 남을 수 있다.
    .replace(/\*{2,}/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  const trimmed = base
    // "제3층 제301호", "301호", "B1층" 이후를 모두 버린다.
    // `\b` 는 쓸 수 없다 — ASCII 기준이라 "층"·"호" 같은 한글 옆에서는 경계가 생기지 않는다.
    // 대신 뒤에 한글이 이어지지 않을 것을 요구해 "호계동"·"호수로" 를 지킨다.
    .replace(/,?\s*제?\s*[\dA-Za-z-]+\s*(?:층|호)(?![가-힣]).*$/u, '')
    // "101동" 같은 숫자+동만 지운다. \d 를 요구하는 것이 "역삼동" 을 지키는 핵심이다.
    .replace(/,?\s*\d+\s*동(?=\s|$)/u, '')
    .replace(/[,\s]+$/u, '')
    .trim()

  return [...new Set([base, trimmed])].filter(Boolean)
}
