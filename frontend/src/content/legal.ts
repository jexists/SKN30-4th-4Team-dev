import type { LegalBlock } from '../components/LegalDoc/blocks'

/** 약관·방침 문서 한 편. 조항(section)들의 모음. */
export type LegalDoc = {
  title: string
  /** 시행일 표기 (예: "2025년 1월 1일"). */
  effectiveDate: string
  /** 조항 앞에 놓는 안내 문단(선택). */
  intro?: string
  sections: {
    /** 장(章) 제목. 이전 section 과 같으면 구분선을 다시 그리지 않는다(선택). */
    chapter?: string
    heading: string
    body: LegalBlock[]
  }[]
}

/** 문자열 배열을 문단 블록으로 감싼다. 단순 조항용 축약 헬퍼. */
function paras(...lines: string[]): LegalBlock[] {
  return lines.map((text) => ({ kind: 'p', text }))
}

